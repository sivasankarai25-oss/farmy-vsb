const DICT: Record<Language, Dict> = { en, ta, ml, hi, ar };

export type TFn = (key: PKey, vars?: Record<string, string | number>) => string;

export function makeT(lang: Language): TFn {
  const dict = (DICT[lang] ?? en) as Partial<Dict>;
  return (key, vars) => {
    let s = dict[key] ?? (en as Dict)[key] ?? "";
    if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]));
    return s;
  };
}

